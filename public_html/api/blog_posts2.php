## 5. Записът е разместен
Единиците не са под единиците, вторият ред при [умножение с двуцифрено число](4-klas-umnozhenie-s-dvutsifreno-chislo.html) не е отместен, пренесеното е написано накриво и се губи. Сметката е вярна, подредбата – не.

**Какво помага:** тетрадка с квадратчета и по една цифра в квадратче. Изненадващо голяма част от „невнимателните“ грешки изчезват само от това.

## 6. Бърза, защото бързането се хвали
Ако у дома и в клас се хвали кой пръв вдига ръка, детето научава, че скоростта е целта, а точността – нещо второстепенно.

**Какво помага:** хвалете довършената и проверена задача, не първата вдигната ръка. „Провери ли?“ преди „готов ли си?“

## Как да разберете коя е причината
Вземете последния тест и погледнете **самите грешки**, не броя им:

- Верен ход, сбъркано междинно число → смята наум или бърза.
- Вярна сметка, отговор на друг въпрос → чете наполовина.
- Отговор с невъзможна големина → няма прикидка.
- Разместени колони, загубено пренесено → записът.
- Грешки само в края на теста → умора или липса на време, не невнимание.

Почти винаги причината е една и съща във всички грешки. Поправя се тя – не всяка задача поотделно.

## Какво да направите тази седмица
1. Изберете **една** от шестте причини – тази, която описва повечето грешки.
2. Въведете съответния навик и го искайте при всяка задача, дори лесната.
3. Не добавяйте втори навик, докато първият не стане автоматичен.

Две седмици са достатъчни за един навик. Шест наведнъж не се получават при никого.

