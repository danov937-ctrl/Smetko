- Ако детето е в 3. клас, [подготовката от 3. клас](podgotovka-nvo-3-klas.html) е за същото, но без бързане.

## Четирите грешки, които струват най-много точки
- **Отговор в друга единица.** Задачата иска километри, детето пише метри. Сметката е вярна, точката я няма.
- **Прескочена задача, която не е върната.** Прескача се с кръгче в полето, не наизуст.
- **Непроверени задачи с избираем отговор.** Там грешката е безвъзвратна – последните пет минути са за тях.
- **Записано решение без записани действия.** В задачите с разширен отговор точките са за решението, не само за числото.

## Какво да не се прави
Да не се говори за изпита всеки ден. Да не се обещава подарък за резултат. Да не се решава по два часа в неделя. Да не се сравнява с дете от другия клас, което „вече решава пробни тестове“.

Седемнайсет седмици по десет минути са близо двайсет и пет часа целенасочена работа. Това е много повече, отколкото изглежда – и достатъчно, ако започнат от дупките, а не от теста.

