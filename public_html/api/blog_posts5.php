Един учебен час – 60 минути (90 за деца със специални образователни потребности), 25 задачи, 100 точки. От тях 16 са с четири възможни отговора, 4 са с кратък отговор, 4 изискват записано решение и една е с три подусловия. Задачите се разпределят в четири области: числа, фигури, измерване и моделиране.

Съдържанието е **материалът от 1. до 4. клас**, нищо извън учебната програма. Няма изненадващи теми – има само теми, които не са затворени.

## Трите периода дотук
**Февруари – март: дупките.** Работи се по темата, в която детето е несигурно, не по изпитния формат. Деление с остатък, таблицата за умножение, мерни единици, лице и обиколка. По десет минути на ден, една тема наведнъж.

**Април: формата.** Чак тук влизат задачите така, както изглеждат на изпита – с избираем отговор, с кратък отговор, със записано решение. Целта не са точки, а да спре да е ново.

**Май: времето.** Цял тест, 60 минути, на един път, веднъж седмично. Тук се учи единственото нещо, което не е математика: как се разпределят шейсет минути между двайсет и пет задачи и кога се прескача задача.

## Защо пробен тест през февруари е грешка
През февруари детето още не е учило част от материала за 4. клас. Пробният тест ще покаже слаб резултат – не защото детето не може, а защото половината теми са за след Великден. Единственото, което остава от такъв тест, е убеждението „няма да се справя“, а то трае до юни.

Пробни тестове се правят, когато материалът е минал. [Пробните тестове по формата на НВО](nvo-4-klas-probni-testove.html) стоят на мястото си и през февруари – просто не са за февруари.

## Колко време на ден
Десет до петнайсет минути дневно, пет дни в седмицата. Това е всичко. Два часа в събота дават по-малко от седем пъти по десет минути, защото паметта работи с повторения, не с продължителност.

През май се добавя едно нещо: един цял тест в неделя, с часовник.

## Откъде се вземат задачи
- [Страницата за НВО в 4. клас](nvo-4-klas-matematika.html) описва формата, областите и какво се иска по всяка от тях.
- [Сборникът с задачи](nvo-sbornik.html) е 95 страници по областите и е свободен за сваляне – без код и без регистрация.
