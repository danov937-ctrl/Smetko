## Кога и отличникът има нужда от помощ
Високите оценки крият две неща. Първото: детето може да е научило рецепти, без да разбира защо работят – вижда се веднага, щом се поиска втори начин или обяснение на глас. Второто: тревожността от грешка. Дете, което плаче за една четворка или къса листа, не е спокойно, а под напрежение – и това се оправя с разговор, не с още задачи.

