**Мълчанието.** Изречението не е оплакване, а въпрос: „Такъв ли ще бъда винаги?“ Ако никой не отговори, детето си отговаря само.

## Какво помага
**Признайте фактите, не присъдата.** „Вярно е, че Мария смята по-бързо. Бързината не е същото като разбиране – а ти разбираш добре задачите с рисунка.“ Детето вярва на този отговор, защото в него има нещо вярно.

**Сменете мярката.** Сравнението с класа не може да се спечели. Сравнението с миналия месец – може. Покажете какво е можело преди четири седмици и какво сега; [отчетът за родителя](otchet.html) върши точно тази работа, защото показва теми и брой решени задачи, а не оценка.

**Назовете нещо конкретно, в което е добро.** Не „ти си умен“, а „ти намираш грешките си сам“ или „ти не се отказваш от дълга задача“. Общата похвала не се помни; конкретната се повтаря наум.

**Направете бързината по-малко важна.** Много деца смятат, че математиката е състезание по скорост, защото така изглежда в класа. Кажете го направо: на контролното има време за всички, а на [НВО в 4. клас](nvo-4-klas-matematika.html) са 60 минути за 25 задачи – повече от две минути на задача.

## Какво да попитаме на родителската среща
Не „как се справя“, а две по-конкретни неща: „Кое му върви добре?“ и „Кое е следващото, върху което да поработим?“ Първият въпрос ви дава нещо вярно, което да кажете на детето; вторият – какво да правите.

Избягвайте въпроса „кой е най-добър в класа“. Отговорът му не променя нищо у дома, а се връща при детето по някакъв начин.

## Когато сравнението е с братче или сестра
Тук боли най-много и се случва най-лесно. Правилото е просто: никога не се сравняват помежду им – нито наяве, нито на шега. Всяко дете се сравнява само със себе си отпреди месец.

Ако по-малкото застига по-голямото в някоя тема, това се казва насаме и на двамата, без публика.

## Какво да направим, ако детето наистина изостава
Сравнението не винаги е въображаемо. Ако изоставането е реално, утехата не стига – трябва да се разбере **коя точно тема** липсва, и да се поправи тя, а не всичко. Един въпрос към учителя върши работа: „Кое е нещото, върху което да поработим у дома?“

После две седмици по десет минути върху тази тема. Детето, което види, че нещо се е оправило, спира да се подрежда в класа – защото вече има друга мярка.

