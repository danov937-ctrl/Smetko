    var E = window.Smetko.MathEngine;
    return { id: 'mon', publisher: 'Учебна програма на МОН', title: 'Общ ред, подходящ за всички учебници', missions: E.ADVENTURE[grade].map(function (m) { return [m[2], m[0] === 'mix' ? null : m[0], m[1], null, m[0]]; }) };
